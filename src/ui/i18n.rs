#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_language_from_code() {
        assert_eq!(Language::from_code("ru"), Language::Ru);
        assert_eq!(Language::from_code("RU"), Language::Ru);
        assert_eq!(Language::from_code("en"), Language::En);
        assert_eq!(Language::from_code("EN"), Language::En);
    }

    #[test]
    fn test_translations_coverage() {
        let keys = [
            TextKey::TabDashboard,
            TextKey::TabVideo,
            TextKey::TabBuffer,
            TextKey::TabAudio,
            TextKey::TabHotkeys,
            TextKey::TabStorage,
            TextKey::SaveReplay,
            TextKey::StartRecord,
            TextKey::TakeScreenshot,
            TextKey::TrayExit,
            TextKey::ToastReplaySaved,
        ];

        for key in keys {
            assert!(!t(key, Language::Ru).is_empty());
            assert!(!t(key, Language::En).is_empty());
        }
    }
}
